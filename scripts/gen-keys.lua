-- Generate assets/js/keys.js from WraithVim's keymap registry, so the site's
-- key reference always matches the real keys.
--
--   nvim --headless --clean -l scripts/gen-keys.lua [path/to/wraithvim]

local site = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
local repo = vim.fn.fnamemodify(arg[1] or (site .. "/../wraithvim"), ":p"):gsub("/$", "")
package.path = repo .. "/lua/?.lua;" .. repo .. "/lua/?/init.lua;" .. package.path

local keymaps = require("wraithvim.config.keymaps")
local vscode = require("wraithvim.config.vscode")
local version = require("wraithvim").version

local function group_of(lhs)
  if keymaps.is_quick(lhs) then
    return "Quick"
  end
  for _, g in ipairs(keymaps.groups) do
    if vim.startswith(lhs, g[1]) then
      return (g[2]:gsub(" %(.*%)$", ""))
    end
  end
  return "Editor"
end

local out, seen = {}, {}
local function add(e, preset, group)
  if e.desc:find("classic terminals", 1, true) or e.desc:find("(Ctrl+Shift+`)", 1, true) then
    return -- alternative byte encodings of a key that is already listed
  end
  local modes = type(e[1]) == "table" and e[1] or { e[1] }
  local id = preset .. e[2] .. e.desc
  if seen[id] then
    return
  end
  seen[id] = true
  out[#out + 1] = {
    keys = keymaps.human(e[2]),
    vim = e[2],
    action = e.desc,
    group = group or group_of(e[2]),
    preset = preset,
    modes = table.concat(modes, ""),
  }
end

for _, e in ipairs(keymaps.defaults()) do
  add(e, "default")
end
for _, e in ipairs(keymaps.lsp()) do
  add(e, "default", "LSP")
end
for _, e in ipairs(vscode.mappings()) do
  add(e, "vscode", "VS Code")
end

local groups = { "Quick" }
for _, g in ipairs(keymaps.groups) do
  groups[#groups + 1] = (g[2]:gsub(" %(.*%)$", ""))
end
vim.list_extend(groups, { "Editor", "VS Code" })

local data = { version = version, groups = groups, keys = out }
local path = site .. "/assets/js/keys.js"
local fd = assert(io.open(path, "w"))
fd:write("// Generated by scripts/gen-keys.lua from WraithVim " .. version .. ". Do not edit.\n")
fd:write("window.WRAITH_KEYS = " .. vim.json.encode(data) .. ";\n")
fd:close()
io.stdout:write(("wrote %d keys (WraithVim %s) to %s\n"):format(#out, version, path))
